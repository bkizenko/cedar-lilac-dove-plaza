import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {readFile,writeFile,unlink} from 'node:fs/promises';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {Game} from '../src/game/sim.ts';
import {assignHusbandry} from '../src/game/husbandry.ts';
const source=new URL('../src/ui/HusbandryControls.tsx',import.meta.url);
const compiled=new URL(`../src/ui/.sheep-husbandry-ui-test-${process.pid}.mjs`,import.meta.url);
await writeFile(compiled,ts.transpileModule(await readFile(source,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}}).outputText);
after(()=>unlink(compiled));
const {HusbandryControls}=await import(compiled.href);
test('native pen controls resume a paused clipped fleece parcel when no sheep has fleece left',()=>{
 const g=new Game();g.reset(42,10);g.enterIsland();g.state.time=100;
 const pen=g.makeBld('pen',20,30,0);g.state.buildings.push(pen);
 const worker=g.state.units.find(u=>u.team===0&&u.type==='worker');assert.ok(worker);
 worker.x=pen.x;worker.z=pen.z;worker.order='hold';worker.jobLock=false;worker.carry=0;
 const sheep={id:g.id(),species:'sheep',x:pen.x,y:g.height(pen.x,pen.z),z:pen.z,facing:0,vx:0,vz:0,wanderT:0,hp:24,maxHp:24,fly:0,scale:1,fleece:{version:1,units:0,grownUnits:4,shearedUnits:4,lastShearedAt:100},team:0,pen:pen.id,sex:'female',born:-200,tamedAt:0,hunger:5,milk:0,pregnancy:0};
 g.state.livestock=[sheep];
 const render=()=>renderToStaticMarkup(React.createElement(HusbandryControls,{engine:{game:g,pushHud(){}},pen:pen.id}));
 assert.match(render(),/<button[^>]*disabled=""[^>]*>Clip sheep fleece</,'empty sheep cannot start another clip');
 worker.itemCargo={rawWool:4};worker.husbandryWork={pen:pen.id,animal:sheep.id,action:'shear',phase:'deliver',progress:0,paused:true};worker.order='idle';
 const button=render().match(/<button[^>]*>Resume fleece delivery<span>/)?.[0];
 assert.ok(button,'actual controls expose the saved delivery resume action');assert.doesNotMatch(button,/disabled/);
 assert.equal(assignHusbandry(g,pen.id,'shear'),true);
 assert.equal(worker.husbandryWork.paused,false);assert.equal(worker.husbandryWork.phase,'deliver');
 assert.equal(worker.itemCargo.rawWool,4);assert.equal(sheep.fleece.units,0);assert.equal(sheep.fleece.shearedUnits,4);
});
