const request=(key,amount,capacity)=>({key,amount,capacity});
const propose=(jobs,id,actors)=>jobs.propose({id,kind:'craft',owner:0,actors,target:1});
test('multi-resource reservations are atomic, aggregated, and amend without counting themselves twice',()=>{
 const ledger=new ReservationLedger();
 assert.equal(ledger.reserve('A',[request('wood',8,10),request('bench',1,1)]).accepted,true);
 assert.equal(ledger.reserve('B',[request('stone',2,5),request('bench',1,1)]).accepted,false);
 assert.equal(ledger.used('stone'),0);
 assert.equal(ledger.reserve('A',[request('wood',11,10)]).accepted,false);
 assert.equal(ledger.used('wood'),8);assert.equal(ledger.used('bench'),1);
 assert.equal(ledger.reserve('A',[request('wood',4,10),request('wood',4,10)]).accepted,true);
 assert.equal(ledger.used('wood'),8);
 ledger.release('A');assert.equal(ledger.used('wood'),0);
 assert.equal(ledger.reserve('B',[request('stone',NaN,5)]).accepted,false);
});
test('one actor cannot own competing jobs; suspended project preserves progress and can resume on another actor',()=>{
 const jobs=new JobCoordinator();propose(jobs,'paid',[1]);propose(jobs,'other',[1,2]);
 assert.equal(jobs.reserve('paid',[request('bench',1,1)]),true);
 jobs.transition('paid','working',17);
 assert.equal(jobs.reserve('other',[request('wood',2,4)]),false);
 assert.equal(jobs.activeJob(2),undefined);assert.equal(jobs.reservations.used('wood'),0);
 assert.equal(jobs.suspend('paid','Explicit command'),true);
 assert.equal(jobs.activeJob(1),undefined);assert.equal(jobs.job('paid').progress,17);
 assert.equal(jobs.reserve('other'),true);
 assert.equal(jobs.resume('paid',[2]),false);
 assert.equal(jobs.job('paid').phase,'suspended');assert.equal(jobs.activeJob(2).id,'other');
 jobs.finish('other');assert.equal(jobs.resume('paid',[3],[request('bench',1,1)]),true);
 assert.equal(jobs.activeJob(3).progress,17);
 assert.equal(jobs.transition('paid','working',16),false);
 jobs.finish('paid');assert.equal(jobs.reservations.used('bench'),0);assert.equal(jobs.activeJob(3),undefined);
 assert.equal(jobs.reserve('paid'),false);assert.equal(jobs.metrics.ownershipConflicts,2);
});
test('tree adapter reconciles legacy crowding, preserves cargo and reconstructs ownership after save/load',()=>{
 let g=new Game();g.reset(123456);g.enterIsland();g.state.units=[];
 const node=g.state.trees.find(n=>n.amount>0);
 const workers=[1,2,3].map(distance=>g.spawnUnit('worker',node.x+distance,node.z,0));
 assert.equal(treeHasRoom(g,node,workers[0]),true);
 assert.equal(workAllocationDiagnostics(g).activeJobs,0,'candidate scans must not claim jobs');
 for(const u of workers){u.order='gather';u.node=node;}
 workers[2].carry=7;workers[2].carryType='wood';
 reconcileTreeWorkers(g);
 assert.equal(workers[2].order,'return');assert.equal(workers[2].carry,7);
 assert.equal(workAllocationDiagnostics(g).activeJobs,2);
 g.state.time+=2;reconcileTreeWorkers(g);
 assert.equal(workAllocationDiagnostics(g).accepted,2,'audits must not double-count ownership');
 assert.equal(treeHasRoom(g,node,workers[2]),false);
 workers[0].order='hold';workers[0].node=null;
 assert.equal(treeHasRoom(g,node,workers[2]),true);
 assert.equal(reserveTreeWorker(g,node,workers[2]),true);
 workers[2].order='gather';workers[2].node=node;
 g=decodeGame(encodeGame(g));reconcileTreeWorkers(g);
 assert.equal(workAllocationDiagnostics(g).activeJobs,2);
 const loaded=g.state.units.find(u=>u.id===workers[2].id);assert.equal(loaded.carry,7);
});
