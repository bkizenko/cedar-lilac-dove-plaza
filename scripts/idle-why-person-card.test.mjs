import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {idleWhy} from '../src/ui/idleWhy.ts';
const source=new URL('../src/ui/WorkerActivity.tsx',import.meta.url);
const hook=registerHooks({load(url,context,next){if(url===source.href)return{format:'module',shortCircuit:true,source:ts.transpileModule(readFileSync(source,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText};return next(url,context);}});
after(()=>hook.deregister());
const {WorkerActivity}=await import(source.href);
const base=()=>({id:1,hp:10,order:'idle',carry:0,itemCargo:{},stuckT:0,tx:0,tz:0,x:0,z:0});
const state={time:100,production:{projects:[]},buildings:[]};
test('idle resident card gives one plain reason from real state, never for busy people',()=>{
 const before=JSON.stringify(state);
 assert.equal(idleWhy(state,base()),'No job open — every task that needs a hand is already staffed');
 assert.match(idleWhy(state,{...base(),resting:true,fatigue:.9}),/^Resting — worn out \(tiredness 90%\)/);
 assert.match(idleWhy(state,{...base(),coldSeconds:12}),/^Too cold to work/);
 assert.match(idleWhy(state,{...base(),sickUntil:150}),/^Sick/);
 assert.equal(idleWhy(state,{...base(),sickUntil:50}),'No job open — every task that needs a hand is already staffed','old illness is not a reason');
 assert.match(idleWhy(state,{...base(),workReason:'Trade load needs more carriers or transport capacity'}),/^Waiting on a hauler — Trade load/);
 assert.match(idleWhy(state,{...base(),workReason:'Need an available adult without tools'}),/^No tool — /);
 assert.match(idleWhy(state,{...base(),order:'hold',workReason:'Waiting for your orders · Auto work is off'}),/^Waiting for your orders/);
 const parked={...state,production:{projects:[{id:4,actorId:1,phase:'stored',blockedReason:'Paid inputs parked at this cache'}]}};
 assert.equal(idleWhy(parked,{...base(),productionProjectId:4}),'Waiting on a hauler — Paid inputs parked at this cache');
 const working={...state,production:{projects:[{id:4,actorId:1,phase:'working',blockedReason:''}]}};
 assert.equal(idleWhy(working,{...base(),productionProjectId:4}),undefined);
 assert.equal(idleWhy(state,{...base(),order:'gather'}),undefined);
 assert.equal(idleWhy(state,{...base(),housingWorkId:3}),undefined,'committed task is not idle');
 assert.equal(idleWhy(state,{...base(),hp:0}),undefined);
 assert.equal(JSON.stringify(state),before);
});
test('person card renders the idle line at a readable size',()=>{
 const html=renderToStaticMarkup(React.createElement(WorkerActivity,{state,resident:{...base(),resting:true,fatigue:.5}}));
 assert.match(html,/data-idle-why/);assert.match(html,/text-base/);assert.match(html,/Resting — worn out \(tiredness 50%\)/);
 const busy=renderToStaticMarkup(React.createElement(WorkerActivity,{state,resident:{...base(),order:'gather'}}));
 assert.doesNotMatch(busy,/data-idle-why/);
});
